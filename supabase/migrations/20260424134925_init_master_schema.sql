CREATE OR REPLACE FUNCTION protect_settled_orders()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.payment_method IS NOT NULL THEN
        RAISE EXCEPTION 'Audit Violation: Cannot modify financial data on a settled order.';
    END IF;
    RETURN NEW;
END;
$$;

-- This allows baristas to update customer_name or profile_id (loyalty points) AFTER payment!
CREATE TRIGGER trigger_protect_settled_orders
BEFORE UPDATE ON public.orders
FOR EACH ROW
WHEN (
    OLD.payment_method IS NOT NULL AND
    (
        OLD.price_total IS DISTINCT FROM NEW.price_total OR
        OLD.cogs_total IS DISTINCT FROM NEW.cogs_total OR
        OLD.payment_method IS DISTINCT FROM NEW.payment_method OR
        OLD.kind IS DISTINCT FROM NEW.kind OR
        OLD.shift IS DISTINCT FROM NEW.shift
    )
)
EXECUTE FUNCTION protect_settled_orders();

CREATE OR REPLACE FUNCTION protect_settled_order_items()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER set search_path = public
AS $$
DECLARE
    ticket_payment_method text;
    target_order_id int;
BEGIN
    -- Handle both UPDATE (NEW/OLD) and DELETE (OLD)
    target_order_id := COALESCE(OLD.order_id, NEW.order_id);

    IF target_order_id IS NULL THEN
        RAISE EXCEPTION 'Audit Violation: Order reference is missing.';
    END IF;

    -- Look up the parent order's payment method
    SELECT payment_method INTO ticket_payment_method
    FROM public.orders WHERE id = target_order_id;

    -- If the ticket is paid, reject the transaction violently!
    IF ticket_payment_method IS NOT NULL THEN
        RAISE EXCEPTION 'Audit Violation: Cannot alter or delete items on a settled ticket. Issue a refund instead.';
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

-- Trigger 1: The restrictive UPDATE (allows fulfillment status changes, blocks tampering)
CREATE TRIGGER trigger_protect_settled_order_items_update
