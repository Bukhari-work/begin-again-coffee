CREATE OR REPLACE FUNCTION protect_settled_order_item_modifiers()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    ticket_payment_method text;
    target_order_item_id int;
BEGIN
    -- 1. Explicit handling per operation
    IF TG_OP = 'DELETE' THEN
        target_order_item_id := OLD.order_item_id;
    ELSIF TG_OP = 'UPDATE' THEN
        -- THE FIX: Hard-block moving modifiers to different items
        IF OLD.order_item_id IS DISTINCT FROM NEW.order_item_id THEN
            RAISE EXCEPTION 'Audit Violation: Modifiers cannot be transferred between order items.';
        END IF;
        target_order_item_id := NEW.order_item_id;
    ELSE
        -- INSERT
        target_order_item_id := NEW.order_item_id;
    END IF;

    -- 2. Fetch payment method (Using JOIN is slightly more performant than a sub-select)
    SELECT o.payment_method
    INTO ticket_payment_method
    FROM public.orders o
    JOIN public.order_items oi ON o.id = oi.order_id
    WHERE oi.id = target_order_item_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Audit Violation: Parent order not found for modifier.';
    END IF;

    -- 3. Block if settled
    IF ticket_payment_method IS NOT NULL THEN
        RAISE EXCEPTION 'Audit Violation: Cannot modify modifiers on a settled ticket. Issue a refund instead.';
    END IF;

    -- 4. Return correct record state
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END;
$$;

