-- 9. TRIGGERS (refresh function)
-- ----------------------------------------------------------------------------

CREATE FUNCTION refresh_item_variation_cogs()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER set search_path = public, pg_temp -- Allows the function to bypass row-level security for the refresh
AS $$
BEGIN
  -- CONCURRENTLY allows the view to be read while it's updating.
  -- Note: CONCURRENTLY requires a UNIQUE index on the materialized view (which you already added!)
  REFRESH MATERIALIZED VIEW CONCURRENTLY public.item_variation_cogs;
END;
$$;

-- Enable the pg_cron extension (if not already enabled)
CREATE EXTENSION IF NOT EXISTS pg_cron;

-- Schedule the refresh for 18:00 UTC (02:00 AM local time) every day
SELECT cron.schedule(
  'nightly-cogs-refresh', -- A unique name for your job
  '0 18 * * *',           -- The cron schedule expression
  $$SELECT public.refresh_item_variation_cogs();$$
);

