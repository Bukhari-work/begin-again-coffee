-- 8. COSTING VIEWS (ANALYTICS)
-- ----------------------------------------------------------------------------

-- A standard view is fine here, as it's a very fast index scan to get the latest price.
CREATE VIEW public.view_ingredient_costs AS
    SELECT DISTINCT ON (ingredient_id)
        ingredient_id,
        purchase_date,
        (cost_total::numeric / NULLIF(quantity, 0)) AS cost_per_unit
    FROM public.purchases
    ORDER BY ingredient_id, purchase_date DESC, id DESC;

CREATE MATERIALIZED VIEW public.item_variation_cogs AS
    WITH resolved_rules AS (
        -- QUERY A: Rules applied directly to the item
        SELECT
            item_id AS target_item_id,
            group_id
        FROM public.modifier_group_rules
        WHERE item_id IS NOT NULL

        UNION -- (Automatically deduplicates accidental overlaps)

        -- QUERY B: Rules applied to the category, expanded to all items in that category
        SELECT
            i.id AS target_item_id,
            mgr.group_id
        FROM public.modifier_group_rules mgr
        JOIN public.items i ON mgr.category_id = i.category_id
        WHERE mgr.category_id IS NOT NULL
    ),
    base_costs AS (
        -- 1. Calculate the physical recipe cost per VARIATION
        SELECT
            iv.id AS variation_id,
            COALESCE(SUM(r.amount * vic.cost_per_unit), 0) AS base_cogs
        FROM public.item_variations iv
        LEFT JOIN public.recipes r ON iv.id = r.item_variation_id
        LEFT JOIN public.view_ingredient_costs vic ON r.ingredient_id = vic.ingredient_id
        GROUP BY iv.id
        ),
    mandatory_group_averages AS (
        -- 2. Calculate mandatory modifiers (like Sugar Level) per ITEM
        SELECT
            i.id AS item_id,
            mg.id AS group_id,
            COALESCE(AVG(m.quantity * vic.cost_per_unit), 0) AS avg_group_cogs,
            COALESCE(AVG(m.price_adjustment), 0) AS avg_group_price_adj
        FROM public.items i
        JOIN resolved_rules rr ON rr.target_item_id = i.id
        JOIN public.modifier_groups mg ON rr.group_id = mg.id
        JOIN public.modifiers m ON mg.id = m.group_id AND m.is_available = true
        LEFT JOIN public.view_ingredient_costs vic ON m.ingredient_id = vic.ingredient_id
        WHERE mg.min_selections >= 1 AND m.behavior = 'STATIC'
        GROUP BY i.id, mg.id
        ),
    modifier_costs AS (
        -- 3. Roll up modifier costs
        SELECT
            item_id,
            SUM(avg_group_cogs) AS total_avg_modifier_cogs,
            SUM(avg_group_price_adj) AS total_avg_modifier_price_adj
        FROM mandatory_group_averages
        GROUP BY item_id
        )

    -- 4. Bring it all together to show exact margins per variation
    SELECT
        iv.id AS variation_id,
        i.name AS item_name,
        iv.name AS variation_name,
        iv.price AS base_price,

        -- Selling Price Math
        (iv.price + COALESCE(mc.total_avg_modifier_price_adj, 0)) AS selling_price,

        -- COGS Math
        bc.base_cogs,
        COALESCE(mc.total_avg_modifier_cogs, 0) AS modifier_cogs,
        (bc.base_cogs + COALESCE(mc.total_avg_modifier_cogs, 0)) AS total_cogs,

        -- Profit Math
        ((iv.price + COALESCE(mc.total_avg_modifier_price_adj, 0)) -
        (bc.base_cogs + COALESCE(mc.total_avg_modifier_cogs, 0))) AS gross_profit,

        -- Margin %
        CASE
            WHEN (iv.price + COALESCE(mc.total_avg_modifier_price_adj, 0)) = 0 THEN 0::numeric
            ELSE ROUND(
                (((iv.price + COALESCE(mc.total_avg_modifier_price_adj, 0)) - (bc.base_cogs + COALESCE(mc.total_avg_modifier_cogs, 0))) /
                NULLIF((iv.price + COALESCE(mc.total_avg_modifier_price_adj, 0)), 0)::numeric) * 100,
                1
            )
        END AS margin_percent

    FROM public.item_variations iv
    JOIN public.items i ON iv.item_id = i.id
    LEFT JOIN base_costs bc ON iv.id = bc.variation_id
    LEFT JOIN modifier_costs mc ON i.id = mc.item_id;

CREATE UNIQUE INDEX idx_item_variation_cogs_id ON public.item_variation_cogs (variation_id);

