-- 1. Create the function that will execute when a user is created
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER set search_path = public
AS $$
BEGIN
  INSERT INTO public.profiles (id, username, role)
  VALUES (
    new.id,
    -- We extract username and role from the metadata JSON we will pass in SvelteKit
    -- new.raw_user_meta_data->>'username',
    COALESCE(
          new.raw_user_meta_data->>'username',
          'user_' || substr(new.id::text, 1, 8)
        ),
    COALESCE(
      (new.raw_user_meta_data->>'role')::public.profile_role,
      'barista'
    )
  );
  RETURN new;
END;
$$;

-- 2. Bind the function to a trigger on the auth.users table
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- ----------------------------------------------------------------------------
-- 11. TRIGGERS (freezing settled ticket functions)
-- ----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION protect_settled_tickets()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER set search_path = public
AS $$
DECLARE
    ticket_payment_method text;
BEGIN
    -- Look up the parent order's payment method
    SELECT payment_method INTO ticket_payment_method
    FROM public.orders WHERE id = OLD.order_id;

    -- If the ticket is paid, reject the transaction violently!
    IF ticket_payment_method IS NOT NULL THEN
        RAISE EXCEPTION 'Audit Violation: Cannot alter the price or quantity of a settled ticket. Issue a refund instead.';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trigger_protect_settled_tickets
BEFORE UPDATE ON order_items
FOR EACH ROW
WHEN (
    OLD.price_base IS DISTINCT FROM NEW.price_base OR
    OLD.price_total IS DISTINCT FROM NEW.price_total OR
    OLD.quantity IS DISTINCT FROM NEW.quantity
)
EXECUTE FUNCTION protect_settled_tickets();
