CREATE TYPE public.fulfillment_state AS ENUM ('preparing', 'served', 'cancelled');
CREATE TYPE public.order_kind AS ENUM ('sale', 'refund');
CREATE TYPE public.payment_type AS ENUM ('cash', 'qris', 'comped');
CREATE TYPE public.shift_type AS ENUM ('day', 'night');
CREATE TYPE public.profile_role AS ENUM ('manager', 'barista');
CREATE TYPE public.modifier_type AS ENUM ('bean', 'syrup', 'milk', 'packaging');
CREATE TYPE public.modifier_behavior AS ENUM ('STATIC', 'DYNAMIC');

-- ----------------------------------------------------------------------------
-- 2. USERS & PROFILES
-- ----------------------------------------------------------------------------
CREATE TABLE public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    username TEXT NOT NULL UNIQUE,
    role public.profile_role NOT NULL DEFAULT 'barista',
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- ----------------------------------------------------------------------------
-- 3. INVENTORY & CATALOG
-- ----------------------------------------------------------------------------
CREATE TABLE public.item_categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,

    CONSTRAINT uniq_category_name UNIQUE (name)
);


CREATE TABLE public.ingredients (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    unit TEXT NOT NULL,
    brand TEXT,
    type TEXT,
    is_active BOOLEAN DEFAULT true NOT NULL,
    category TEXT NOT NULL
);

CREATE UNIQUE INDEX uniq_active_ingredient_name
ON public.ingredients (name)
WHERE is_active = true;

CREATE TABLE public.items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    price INTEGER NOT NULL CONSTRAINT chk_items_price_positive CHECK (price >= 0),
    category_id INTEGER REFERENCES public.item_categories(id) ON DELETE SET NULL,
    description TEXT,
    featured_rank SMALLINT DEFAULT 0 NOT NULL,
    is_available BOOLEAN DEFAULT true NOT NULL,
    image_url TEXT
);

CREATE UNIQUE INDEX uniq_active_item_per_category
ON public.items (category_id, name)
WHERE is_available = true;

CREATE TABLE public.item_variations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id INTEGER NOT NULL REFERENCES public.items(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    price INTEGER NOT NULL CONSTRAINT chk_item_variations_price_positive CHECK (price >= 0),
    is_available BOOLEAN DEFAULT true NOT NULL
);

CREATE UNIQUE INDEX uniq_item_variation_name
ON public.item_variations (item_id, LOWER(TRIM(name)))
WHERE is_available = true;

-- ----------------------------------------------------------------------------
-- 4. MENU CUSTOMIZATIONS (MODIFIERS)
-- ----------------------------------------------------------------------------
CREATE TABLE public.modifier_groups (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    min_selections SMALLINT DEFAULT 0 NOT NULL,
    max_selections SMALLINT,

    CONSTRAINT uniq_modifier_group_name UNIQUE (name)
);

CREATE TABLE public.modifier_group_rules (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id INTEGER NOT NULL REFERENCES public.modifier_groups(id) ON DELETE CASCADE,
    category_id INTEGER REFERENCES public.item_categories(id) ON DELETE CASCADE,
    item_id INTEGER REFERENCES public.items(id) ON DELETE CASCADE,

    CONSTRAINT chk_category_OR_item_logic CHECK (
        (category_id IS NOT NULL AND item_id IS NULL)
        OR
        (category_id IS NULL AND item_id IS NOT NULL)
    )
);
-- Prevent duplicates
CREATE UNIQUE INDEX uniq_mgr_item
ON public.modifier_group_rules(group_id, item_id)
WHERE item_id IS NOT NULL;

CREATE UNIQUE INDEX uniq_mgr_category
ON public.modifier_group_rules(group_id, category_id)
WHERE category_id IS NOT NULL;

CREATE TABLE public.modifiers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id INTEGER NOT NULL REFERENCES public.modifier_groups(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    price_adjustment INTEGER DEFAULT 0 NOT NULL,
    ingredient_id INTEGER REFERENCES public.ingredients(id),
    quantity INTEGER DEFAULT 1 NOT NULL CONSTRAINT chk_modifiers_qty_positive CHECK (quantity > 0),
    behavior public.modifier_behavior DEFAULT 'STATIC' NOT NULL,
    is_available BOOLEAN DEFAULT true NOT NULL,
    dependency_source INTEGER NULL REFERENCES public.modifiers_groups(id)

    CONSTRAINT chk_modifier_dependency_logic CHECK (
        (behavior = 'STATIC' AND dependency_source IS NULL)
        OR
        (behavior = 'DEPENDENT' AND dependency_source IS NOT NULL)
    )

    CONSTRAINT chk_dependency_group_single_select CHECK (
        dependency_source IS NULL OR
        dependency_source IN (
            SELECT id FROM modifier_groups WHERE max_selections = 1
      )
    )
);

CREATE UNIQUE INDEX uniq_active_modifier_per_group
ON public.modifiers (group_id, LOWER(TRIM(name)))
WHERE is_available = true;

-- ----------------------------------------------------------------------------
-- 5. PURCHASING & RECIPES
