CREATE TABLE public.purchases (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_id INTEGER REFERENCES public.ingredients(id) ON DELETE RESTRICT,
    purchase_date DATE DEFAULT CURRENT_DATE NOT NULL,
    quantity INTEGER NOT NULL CONSTRAINT chk_purchases_qty_positive CHECK (quantity > 0),
    cost_total INTEGER NOT NULL CONSTRAINT chk_purchases_cost_positive CHECK (cost_total >= 0),
    supplier TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    notes TEXT
);

CREATE TABLE public.recipes (
    item_variation_id INTEGER NOT NULL REFERENCES public.item_variations(id) ON DELETE CASCADE,
    ingredient_id INTEGER NOT NULL REFERENCES public.ingredients(id) ON DELETE CASCADE,
    amount INTEGER NOT NULL CONSTRAINT chk_recipes_amount_positive CHECK (amount > 0),
    PRIMARY KEY (item_variation_id, ingredient_id)
);

-- ----------------------------------------------------------------------------
-- 6. TRANSACTIONS (THE POS ENGINE)
-- ----------------------------------------------------------------------------
CREATE TABLE public.orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_order_id INTEGER REFERENCES public.orders(id) ON DELETE RESTRICT,
    customer_name TEXT,
    profile_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    payment_method public.payment_type,
    shift public.shift_type DEFAULT 'day' NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    price_total INTEGER DEFAULT 0 NOT NULL,
    cogs_total NUMERIC(12,2) DEFAULT 0 NOT NULL,
    kind public.order_kind DEFAULT 'sale' NOT NULL,

    CONSTRAINT chk_orders_kind_parent_logic CHECK (
        (kind = 'sale' AND parent_order_id IS NULL)
        OR
        (kind = 'refund' AND parent_order_id IS NOT NULL)
    ),

    CONSTRAINT chk_orders_signed_math CHECK (
        -- Sales must have zero or positive revenue
        (kind = 'sale' AND price_total >= 0)
        OR
        -- Refunds must have zero or negative revenue, and zero COGS
        (kind = 'refund' AND price_total <= 0 AND cogs_total = 0)
    )
);

COMMENT ON COLUMN public.orders.payment_method IS 'NULL means unpaid order';

CREATE TABLE public.order_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    original_order_item_id INTEGER REFERENCES public.order_items(id) NULL,
    item_variation_id INTEGER REFERENCES public.item_variations(id) ON DELETE SET NULL,

    -- The Dual-Status Matrix
    ledger_status public.ledger_state DEFAULT 'active' NOT NULL,
    fulfillment_status public.fulfillment_state DEFAULT 'preparing' NOT NULL,

    quantity INTEGER DEFAULT 1 NOT NULL,
    price_base INTEGER NOT NULL,
    cogs_base NUMERIC(10,2) DEFAULT 0 NOT NULL,
    price_total INTEGER DEFAULT 0 NOT NULL,
    cogs_total NUMERIC(12,2) DEFAULT 0 NOT NULL,

    CONSTRAINT chk_order_items_base_positive CHECK (
        -- Base values are immutable truths, always positive
        price_base >= 0 AND cogs_base >= 0
    ),
    CONSTRAINT chk_order_items_signed_quantity CHECK (
        -- Normal items are positive quantities
        (ledger_status IN ('active', 'voided') AND quantity >= 0)
        OR
        -- Refunded clone items MUST be negative quantities, and capture zero COGS
        (ledger_status = 'refunded' AND quantity <= 0 AND cogs_total = 0)
    ),
    CONSTRAINT chk_order_items_total_math CHECK (
        -- Enforce that the denormalized total is ALWAYS the mathematical product
        price_total = (price_base * quantity)
    )
);

CREATE TABLE public.order_item_modifiers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id INTEGER NOT NULL REFERENCES public.order_items(id) ON DELETE CASCADE,
    modifier_id INTEGER NOT NULL REFERENCES public.modifiers(id),
    quantity INTEGER DEFAULT 1 NOT NULL,
    price_base INTEGER NOT NULL,
    cogs_base NUMERIC(10,2) DEFAULT 0 NOT NULL,
    resolved_ingredient_id INTEGER NULL REFERENCES public.ingredients(id) ON DELETE CASCADE,

    CONSTRAINT uniq_modifier_per_order_item UNIQUE (order_item_id, modifier_id),
    CONSTRAINT chk_oim_qty_not_zero CHECK (quantity != 0),
    CONSTRAINT  chk_oim_cogs_positive CHECK (cogs_base >= 0)
);

